// Supported languages
const supportedLangs = ['es', 'ca', 'en', 'fr', 'de'];

// Detect browser language
function detectBrowserLanguage() {
    const browserLang = navigator.language || navigator.userLanguage;
    const shortLang = browserLang.split('-')[0].toLowerCase();
    return supportedLangs.includes(shortLang) ? shortLang : 'es';
}

// Get saved language or detect
function getCurrentLanguage() {
    let saved;
    try { saved = localStorage.getItem('cv-language'); } catch { /* Optional preference storage. */ }
    if (saved && supportedLangs.includes(saved)) return saved;
    return detectBrowserLanguage();
}

// Set language
function setLanguage(lang) {
    if (!supportedLangs.includes(lang)) lang = 'es';

    try { localStorage.setItem('cv-language', lang); } catch { /* The page still works without storage. */ }
    document.documentElement.lang = lang;

    // Update all translatable elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang]?.[key] || translations.es[key]) {
            el.textContent = translations[lang]?.[key] || translations.es[key];
        }
    });

    // Update active button
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
        btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', translations[lang]?.[el.dataset.i18nAria] || translations.es[el.dataset.i18nAria]));
    const current = document.getElementById('current-lang');
    if (current) current.textContent = lang.toUpperCase();
}

// Initialize language on load
function initLanguage() {
    const lang = getCurrentLanguage();
    setLanguage(lang);
}

// Export for use in main.js
window.i18n = { setLanguage, getCurrentLanguage, initLanguage, t: key => translations[document.documentElement.lang]?.[key] || translations.es[key] || key };
